;WITH cur AS (
  SELECT UPPER(o.name) nm, SUM(p.rows) rows_n
    FROM sys.partitions p JOIN sys.objects o ON o.object_id = p.object_id
   WHERE o.schema_id = SCHEMA_ID('VPLUS40') AND o.type = 'U' AND p.index_id IN (0,1)
   GROUP BY o.name
)
SELECT COALESCE(c.nm, b.nm) AS table_name,
       b.rows_n AS rows_ERPH202611A,
       c.rows_n AS rows_170,
       c.rows_n - b.rows_n AS diff_170_minus_ERPH
  FROM cur c FULL OUTER JOIN @base b ON b.nm = c.nm
 WHERE ISNULL(c.rows_n,-1) <> ISNULL(b.rows_n,-1)
 ORDER BY ABS(ISNULL(c.rows_n,0) - ISNULL(b.rows_n,0)) DESC, 1;
